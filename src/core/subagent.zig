//! In-process subagent seam: request/result shapes, bounds, validation and the
//! service function-pointer contract. App owns child Runtimes, credentials,
//! approval mapping, jobs and cleanup; Tools calls this contract only, so there
//! is no Tools -> App dependency cycle. No filesystem, network or UI code here.
//!
//! The parent keeps reasoning and communication while a child runs: `run` is
//! only a START operation, while `get`, `send`, `cancel`, `active` and the
//! task-lifecycle hooks operate on the host's current-root jobs. A child has
//! no recursive service; its only channel is `ParentChannel`.

const std = @import("std");
const protocol = @import("protocol.zig");

/// Bounds are part of the tool contract; keep them centralized instead of
/// scattering per-call fallbacks.
pub const max_task_bytes: usize = 8192;
pub const max_context_bytes: usize = 16384;
/// Report/payload cap applied by the App before it encodes the tool result.
/// Tools never re-truncates or re-encodes the encoded JSON it receives.
pub const max_report_bytes: usize = 16384;
/// Delegations per accepted root task. A started failure still consumes a slot;
/// only a genuinely new accepted task resets the counter.
pub const max_runs_per_task: u32 = 4;
/// Job identifiers are generated by the host, monotonic and never reused within
/// a root task. They are opaque to Tools beyond these bounds.
pub const max_id_bytes: usize = 64;
/// One steering/reply body in either direction.
pub const max_message_bytes: usize = 4096;
/// Successful messages per direction per job.
pub const max_messages_per_direction: u32 = 32;
/// Unread child messages retained for a later parent `get`.
pub const max_unread_messages: u32 = 8;
/// Optional intermediate child progress body.
pub const max_progress_bytes: usize = 2048;
/// Stop-time reminders per accepted root task before a child interaction pause.
pub const max_finish_reminders: u8 = 3;

/// One delegated task. Both slices are borrowed request data, owned by the
/// caller's arena; the service must copy anything it keeps.
pub const Request = struct {
    task: []const u8,
    /// Optional parent-selected reference material, never authorization.
    context: ?[]const u8 = null,
};

/// Snapshot or wait query for a started job.
pub const Query = struct { id: []const u8, wait: bool = true };

/// A parent message. When the child is waiting, it fills the independent reply
/// slot; otherwise it is a non-blocking steering enqueue for the child Inbox.
pub const Send = struct { id: []const u8, message: []const u8 };

/// Cancel and join exactly one job; an ordinary job cancel never cancels the
/// parent accepted task.
pub const Cancel = struct { id: []const u8 };

/// A child message to the parent. `wait_for_reply` makes the tool call wait for
/// a parent reply instead of fabricating a user turn.
pub const Message = struct { message: []const u8, wait_for_reply: bool = false };

/// The child's bounded outcome. `text` is ALREADY the encoded tool-result JSON
/// (status including paused, report/usage/detail, ...); the App does the encoding.
/// Ownership is conditional: an ordinary result is owned by the allocator passed
/// to the callback, while cancellation/cleanup fallbacks may be static literals.
/// Callers must therefore not free `text` unconditionally. Tools maps `text` and
/// the flags onto `runtime.Execution` verbatim and never re-encodes or
/// re-truncates it, so the bytes remain bounded by the App's `max_report_bytes`
/// and Runtime's fitResult.
pub const Result = struct {
    text: []const u8,
    is_error: bool = false,
    /// The PARENT call was canceled. A child job reaching a canceled terminal
    /// state does not set this; only the parent Execution cancellation matters.
    canceled: bool = false,
    truncated: bool = false,
    /// A child command group or job could not be confirmed stopped. This
    /// outranks cancellation: the parent Runtime must poison instead of
    /// continuing.
    cleanup_failed: bool = false,
};

/// Strict request validation: UTF-8, non-empty task, no NUL bytes, hard caps.
pub fn validate(request: Request) !void {
    const task = request.task;
    if (task.len == 0 or task.len > max_task_bytes) return error.InvalidSubagentTask;
    if (!std.unicode.utf8ValidateSlice(task) or std.mem.findScalar(u8, task, 0) != null)
        return error.InvalidSubagentTask;
    if (request.context) |context| {
        if (context.len > max_context_bytes) return error.InvalidSubagentContext;
        if (!std.unicode.utf8ValidateSlice(context) or std.mem.findScalar(u8, context, 0) != null)
            return error.InvalidSubagentContext;
    }
}

pub fn validateId(id: []const u8) !void {
    if (id.len == 0 or id.len > max_id_bytes) return error.InvalidSubagentId;
    if (!std.unicode.utf8ValidateSlice(id) or std.mem.findScalar(u8, id, 0) != null)
        return error.InvalidSubagentId;
}

fn validateBody(message: []const u8) !void {
    if (message.len == 0 or message.len > max_message_bytes) return error.InvalidSubagentMessage;
    if (!std.unicode.utf8ValidateSlice(message) or std.mem.findScalar(u8, message, 0) != null)
        return error.InvalidSubagentMessage;
}

pub fn validateQuery(query: Query) !void {
    try validateId(query.id);
}

pub fn validateSend(send: Send) !void {
    try validateId(send.id);
    try validateBody(send.message);
}

pub fn validateCancel(cancel: Cancel) !void {
    try validateId(cancel.id);
}

pub fn validateMessage(message: Message) !void {
    try validateBody(message.message);
}

pub const Bounded = struct { text: []const u8, truncated: bool };

/// App-side helper: copy at most max_report_bytes of a valid UTF-8 report,
/// backing up from a split scalar so truncation never produces invalid UTF-8.
/// Retained for the App encoder; Tools must not apply it to encoded JSON.
pub fn boundReport(a: std.mem.Allocator, text: []const u8) !Bounded {
    if (!std.unicode.utf8ValidateSlice(text)) return error.InvalidSubagentReport;
    if (text.len <= max_report_bytes) return .{ .text = try a.dupe(u8, text), .truncated = false };
    var end: usize = max_report_bytes;
    var backed: u3 = 0;
    while (end > 0 and backed < 3 and (text[end] & 0xc0) == 0x80) : (backed += 1) end -= 1;
    return .{ .text = try a.dupe(u8, text[0..end]), .truncated = true };
}

/// Small per-root-task delegation budget. The owner resets it only when a new
/// accepted task starts (`Service.beginTask`), never on a tool call or redraw.
pub const Runs = struct {
    used: u32 = 0,

    pub fn reset(self: *Runs) void {
        self.used = 0;
    }

    /// Consume one slot before starting a run; a failed start is not returned.
    pub fn consume(self: *Runs) !void {
        if (self.used >= max_runs_per_task) return error.SubagentRunsExhausted;
        self.used += 1;
    }
};

/// Host-provided child service. `run_fn` starts a job and returns immediately
/// with its id; it must honour `cancel`, own its child resources and finish
/// cleanup before returning. Optional callbacks are no-ops/wrappers when absent.
pub const Service = struct {
    context: *anyopaque,
    /// Start operation: register the job and return immediately. The encoded
    /// result still includes `{id,status:"running"}`, even if the job already
    /// finished; the parent must collect it with `get`.
    run_fn: *const fn (*anyopaque, std.mem.Allocator, Request, *const protocol.Cancellation) anyerror!Result,
    /// Called once per newly accepted root task (before its first model call).
    /// `cancel` is the accepted-root token (watchdog target), never a local
    /// tool-call token.
    begin_task_fn: ?*const fn (*anyopaque, *const protocol.Cancellation) void = null,
    /// Pure readiness/poison check; failures surface as a tool error. It must
    /// not enforce the start quota, so a 5th get/send is not blocked.
    check_fn: ?*const fn (*anyopaque) anyerror!void = null,
    /// Snapshot (`wait=false`) or explicit-message/terminal wait (`wait=true`).
    get_fn: ?*const fn (*anyopaque, std.mem.Allocator, Query, *const protocol.Cancellation) anyerror!Result = null,
    /// Reply slot or non-blocking steering enqueue; must copy the message.
    send_fn: ?*const fn (*anyopaque, std.mem.Allocator, Send, *const protocol.Cancellation) anyerror!Result = null,
    /// Cancel and join one job, returning its final cancellation/cleanup state.
    cancel_fn: ?*const fn (*anyopaque, std.mem.Allocator, Cancel, *const protocol.Cancellation) anyerror!Result = null,
    /// True while a job of the current root is running or uncollected.
    active_fn: ?*const fn (*anyopaque) bool = null,
    /// Before an Inbox seal of a normal stop: return a bounded host-status/ID
    /// hint, or null when nothing remains. Allocated with the passed allocator;
    /// Runtime copies it into the stable history arena.
    before_finish_fn: ?*const fn (*anyopaque, std.mem.Allocator, *const protocol.Cancellation) anyerror!?[]const u8 = null,
    /// Unified end-of-root-task cleanup: cancel/join/release or retain every job.
    end_task_fn: ?*const fn (*anyopaque, *const protocol.Cancellation) anyerror!void = null,

    pub fn beginTask(self: Service, token: *const protocol.Cancellation) void {
        if (self.begin_task_fn) |callback| callback(self.context, token);
    }

    pub fn checkReady(self: Service) !void {
        if (self.check_fn) |callback| try callback(self.context);
    }

    /// `run_fn` returns already-encoded, bounded tool-result JSON. Cleanup
    /// failure dominates cancellation: a possibly live child command group must
    /// poison the parent even if the child also stopped for cancellation.
    pub fn run(self: Service, a: std.mem.Allocator, request: Request, token: *const protocol.Cancellation) anyerror!Result {
        var result = try self.run_fn(self.context, a, request, token);
        if (result.cleanup_failed) result.is_error = true;
        return result;
    }

    pub fn get(self: Service, a: std.mem.Allocator, query: Query, token: *const protocol.Cancellation) anyerror!Result {
        try validateQuery(query);
        const callback = self.get_fn orelse return error.SubagentUnavailable;
        var result = try callback(self.context, a, query, token);
        if (result.cleanup_failed) result.is_error = true;
        return result;
    }

    pub fn send(self: Service, a: std.mem.Allocator, message: Send, token: *const protocol.Cancellation) anyerror!Result {
        try validateSend(message);
        const callback = self.send_fn orelse return error.SubagentUnavailable;
        var result = try callback(self.context, a, message, token);
        if (result.cleanup_failed) result.is_error = true;
        return result;
    }

    pub fn cancel(self: Service, a: std.mem.Allocator, request: Cancel, cancel_token: *const protocol.Cancellation) anyerror!Result {
        try validateCancel(request);
        const callback = self.cancel_fn orelse return error.SubagentUnavailable;
        var result = try callback(self.context, a, request, cancel_token);
        if (result.cleanup_failed) result.is_error = true;
        return result;
    }

    pub fn active(self: Service) bool {
        const callback = self.active_fn orelse return false;
        return callback(self.context);
    }

    pub fn beforeFinish(self: Service, a: std.mem.Allocator, token: *const protocol.Cancellation) anyerror!?[]const u8 {
        const callback = self.before_finish_fn orelse return null;
        return callback(self.context, a, token);
    }

    pub fn endTask(self: Service, token: *const protocol.Cancellation) anyerror!void {
        const callback = self.end_task_fn orelse return;
        return callback(self.context, token);
    }
};

/// The child's only communication channel. It cannot reach the parent Runtime,
/// permissions, job control or another service.
pub const ParentChannel = struct {
    context: *anyopaque,
    message_fn: *const fn (*anyopaque, std.mem.Allocator, Message, *const protocol.Cancellation) anyerror!Result,

    pub fn message(self: ParentChannel, a: std.mem.Allocator, request: Message, cancel: *const protocol.Cancellation) anyerror!Result {
        try validateMessage(request);
        var result = try self.message_fn(self.context, a, request, cancel);
        if (result.cleanup_failed) result.is_error = true;
        return result;
    }
};
