import time

ROWS = 24
COLUMNS = (120, 100)
KEY = 'owned-memory-background-fixture-key'
HELPER_PREFIX = 'Extract only durable, reusable knowledge'
# Prompt 2 shares the "review"/"concise" tokens of the committed fact so the
# knowledge store's lexical retrieval actually returns it; that is what makes the
# queued job's `related` evidence meaningful rather than incidental.
PROMPTS = (
    'I prefer concise code reviews.',
    'Please keep my code review concise while the first memory job is blocked.',
    'Third question after the memory work settles.',
)
ANSWERS = ('answer-one-proof', 'answer-two-proof', 'answer-three-proof')
FACT = 'Prefers concise code reviews.'
QUOTE = 'prefer concise code reviews'
ACTIVE = 'Memory: extracting'
TERMINAL_SKIPPED = 'Memory: no new durable entries'
SAVED_PATH = '.thin/memory/preferences-review-style.md'
RETIRED_PATHS = ('.thin/memory/jobs', '.thin/memory/jobs-owner', '.thin/mem-jobs', '.thin/mem-jobs-owner')
CONTEXT_PREFIX = '[Context material'
VERSION = re.compile(r'[0-9a-f]{64}')
WARNING_MARKERS = ('Saved thinking level not applied', 'awaiting model capabilities')


def load_idle_fixture():
    """Borrow Screen/CSI/FRAME_END/_IDLE_COMPOSER without running that fixture."""
    path = Path(__file__).resolve().parent / 'idle_enter_mock.py'
    source = path.read_text(encoding='utf-8')
    assert "\nif __name__ == '__main__':" in source, 'idle fixture lost its main guard'
    spec = importlib.util.spec_from_file_location('thin_owned_idle_enter_mock', path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    assert module.__name__ != '__main__'
    spec.loader.exec_module(module)
    # The guard means loading only defines classes/regexes: no server, no PTY and
    # no application process may have been started by the import.
    assert module.Service.requests == [], 'idle fixture main ran on import'
    assert not module.Service.release.is_set(), 'idle fixture gate ran on import'
    assert callable(module.Screen) and module.FRAME_END and module._IDLE_COMPOSER
    return module


IDLE = load_idle_fixture()
Screen = IDLE.Screen
FRAME_END = IDLE.FRAME_END
SYNC_BEGIN = IDLE.SYNC_BEGIN


class Control:
    """Per-run wire/HTTP state shared with the owned server's handler threads."""

    def __init__(self):
        self.lock = threading.Lock()
        self.failure = None
        self.expected = []
        self.primary = 0
        self.helper = 0
        self.materials = []
        self.helper1_arrived = threading.Event()
        self.release1 = threading.Event()
        self.helper2_arrived = threading.Event()
        self.release2 = threading.Event()
        self.helper3_arrived = threading.Event()
        self.release3 = threading.Event()
        self.helper3_canceled = threading.Event()
        self.helper3_responded = False

    def fail(self, error):
        with self.lock:
            if self.failure is None:
                self.failure = error

    def expect(self, prompt):
        with self.lock:
            self.expected.append(prompt)

    def next_primary(self):
        with self.lock:
            index = self.primary
            self.primary += 1
            return index

    def next_helper(self):
        with self.lock:
            index = self.helper
            self.helper += 1
            return index


class MemoryService(http.server.BaseHTTPRequestHandler):
    control = None

    def log_message(self, *_):
        pass

    def do_GET(self):
        self.control.fail(AssertionError(f'unexpected metadata/network GET {self.path!r}'))
        self.send_error(500)

    def do_POST(self):
        control = self.control
        try:
            assert self.path == '/v1/chat/completions', f'unexpected request path {self.path!r}'
            assert self.headers.get('Authorization') == f'Bearer {KEY}', 'credential header mismatch'
            size = int(self.headers['Content-Length'])
            assert 0 < size <= 512 * 1024, 'request byte bound'
            body = json.loads(self.rfile.read(size))
            messages = body.get('messages') or []
            helper = (bool(messages) and messages[0].get('role') == 'system' and
                      isinstance(messages[0].get('content'), str) and
                      messages[0]['content'].startswith(HELPER_PREFIX))
            if helper:
                self.helper_request(body)
            else:
                self.primary_request(body)
        except Exception as error:
            control.fail(error)
            try:
                self.send_error(500)
            except OSError:
                pass

    def primary_request(self, body):
        control = self.control
        index = control.next_primary()
        with control.lock:
            expected = list(control.expected)
        assert index < len(expected), f'unexpected extra primary request #{index + 1}'
        messages = body.get('messages') or []
        turns = [m.get('content') for m in messages
                 if m.get('role') == 'user' and isinstance(m.get('content'), str)
                 and not m['content'].startswith(CONTEXT_PREFIX)]
        assert turns == expected[:index + 1], f'primary {index + 1} canonical user turn mismatch'
        assert all('Memory:' not in m.get('content', '') for m in messages
                   if m.get('role') in ('user', 'assistant') and isinstance(m.get('content'), str)), \
            f'primary {index + 1} replayed a Memory notice'
        if index == 1:
            assert not control.release1.is_set(), 'prompt 2 was admitted only after Memory 1 was released'
        self.sse(ANSWERS[index])

    def helper_request(self, body):
        control = self.control
        index = control.next_helper()
        assert index < len(PROMPTS), f'unexpected extra Memory request #{index + 1}'
        messages = body.get('messages') or []
        assert [m.get('role') for m in messages] == ['system', 'user'], \
            f'Memory request is not instruction+material: {[m.get("role") for m in messages]!r}'
        assert body.get('tools') in (None, []), 'Memory extractor received tools'
        material = json.loads(messages[1]['content'])
        sources = material.get('sources')
        assert isinstance(sources, list) and sources, 'Memory material has no evidence'
        assert len(sources) == 1, f'Memory {index + 1} material sources {len(sources)} != 1'
        for source in sources:
            assert source.get('kind') == 'user', f'non-user evidence in Memory material: {source.get("kind")!r}'
            assert isinstance(source.get('text'), str) and KEY not in source['text'], 'credential in evidence'
        assert sources[0]['text'] == PROMPTS[index], f'Memory {index + 1} evidence {sources[0]["text"]!r}'
        assert KEY not in json.dumps(material), 'credential entered Memory material'
        with control.lock:
            control.materials.append(material)
        if index == 0:
            control.helper1_arrived.set()
            assert control.release1.wait(30), 'Memory 1 gate timed out'
            text = sources[0]['text']
            assert QUOTE in text, f'fixture quote is not a literal source substring: {text!r}'
            items = [{'category': 'preferences', 'topic': 'review-style', 'content': FACT,
                      'source_id': sources[0]['id'], 'quote': QUOTE,
                      'expected_version': None, 'expires_at_ms': None}]
            self.sse(json.dumps({'items': items}))
            return
        if index == 1:
            control.helper2_arrived.set()
            assert control.release1.is_set(), 'Memory 2 started before Memory 1 finished'
            assert self.related_committed(material), \
                f'queued Memory 2 material lacks the committed fact/version: {material.get("related")!r}'
            assert control.release2.wait(30), 'Memory 2 gate timed out'
            self.sse(json.dumps({'items': []}))
            return
        control.helper3_arrived.set()
        while not control.release3.wait(0.02):
            if self.peer_closed():
                control.helper3_canceled.set()
                return  # never release a valid response for a canceled request
        control.helper3_responded = True
        self.sse(json.dumps({'items': []}))

    @staticmethod
    def related_committed(material):
        for entry in material.get('related') or []:
            if (entry.get('category') == 'preferences' and entry.get('topic') == 'review-style'
                    and entry.get('content') == FACT and VERSION.fullmatch(str(entry.get('version')))):
                return True
        return False

    def peer_closed(self):
        try:
            ready, _, _ = select.select([self.connection], [], [], 0)
            if not ready:
                return False
            return self.connection.recv(1, socket.MSG_PEEK) == b''
        except OSError:
            return True

    def sse(self, content):
        self.send_response(200)
        self.send_header('Content-Type', 'text/event-stream')
        self.send_header('Cache-Control', 'no-store')
        self.end_headers()
        frames = (
            {'choices': [{'index': 0, 'delta': {'content': content}, 'finish_reason': None}]},
            {'choices': [{'index': 0, 'delta': {}, 'finish_reason': 'stop'}],
             'usage': {'prompt_tokens': 64, 'completion_tokens': 16, 'total_tokens': 80}},
        )
        for frame in frames:
            self.wfile.write(b'data: ' + json.dumps(frame).encode() + b'\n\n')
        self.wfile.write(b'data: [DONE]\n\n')
        self.wfile.flush()


def row_text(screen, index):
    return ''.join(screen.grid[index]).rstrip(' ')


def footer_state(screen):
    """Settled footer view: the normalized Memory label, or None while unsettled.

    Never raises: gates must be able to poll. A layout violation simply fails the
    gate, and assert_footer() then reports the exact rows.
    """
    if screen.row != len(screen.grid) - 1:
        return None
    rows = [row_text(screen, i) for i in range(len(screen.grid))]
    hint = rows[screen.row - 1]
    if not hint.startswith('Memory:'):
        return None
    if rows[screen.row - 2] != '':
        return None
    if sum(text.startswith('Memory:') for text in rows) != 1:
        return None
    return hint.split('|')[0].rstrip()


def assert_footer(screen, expected):
    """Exactly one Memory hint between the blank separator and composer row."""
    rows = [row_text(screen, i) for i in range(len(screen.grid))]
    row = screen.row
    assert row == len(screen.grid) - 1, f'idle composer is not on the physical bottom row ({row})'
    hint = rows[row - 1]
    assert rows[row - 2] == '', f'blank separator above the Memory hint is missing: {rows[row - 2]!r}'
    hints = [text for text in rows if text.startswith('Memory:')]
    assert len(hints) == 1, f'Memory hint is not unique on the screen: {hints!r}'
    assert hints[0] == hint, 'the Memory hint is not the row directly above the composer'
    label = hint.split('|')[0].rstrip()
    assert label.startswith(expected), f'Memory footer is {label!r}, expected prefix {expected!r}'
    suffix = label[len(expected):]
    if suffix:
        assert re.search(r'\d', suffix) and 'queue' in suffix.lower(), \
            f'queued Memory suffix is not a count: {suffix!r}'
    assert 'S:' not in hint and 'F:' not in hint, \
        f'Memory status leaked primary steering/follow-up counters: {hint!r}'
    return hint


def assert_no_memory_transcript(screen):
    """Only the current footer may contain a Memory notice in the visible frame.

    Previously displayed footers can legitimately remain in native scrollback.
    """
    rows = [row_text(screen, i) for i in range(len(screen.grid))]
    assert sum('Memory:' in text for text in rows) == 1, 'extra or missing visible Memory row'
    assert 'Memory:' in rows[screen.row - 1], 'Memory notice outside the footer'


def run(app, columns):
    control = Control()
    MemoryService.control = control
    server = http.server.ThreadingHTTPServer(('127.0.0.1', 0), MemoryService)
    server.daemon_threads = True
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    master = slave = None
    child = None
    pgid = None
    with tempfile.TemporaryDirectory(prefix='thin-memory-background-') as base:
        home, project = Path(base) / 'home', Path(base) / 'project'
        # An owned short runtime base keeps the foreground AF_UNIX worker inside
        # this fixture instead of the shared /tmp fallback for this uid.
        runtime = Path(base) / 'r'
        runtime.mkdir(mode=0o700)
        assert (runtime.stat().st_mode & 0o777) == 0o700, 'owned runtime must be 0700'
        assert len(str(runtime)) + 14 + 32 + 5 <= 107, 'AF_UNIX socket path budget exceeded'
        (home / '.thin').mkdir(parents=True)
        project.mkdir()
        # Metadata refresh is disabled on the command line; automatic Memory is
        # left at its default On by omitting `memory`.
        config = {
            'llm': {'default': 'local/fixture-model', 'providers': {'local': {
                'base_url': f'http://127.0.0.1:{server.server_port}/v1',
                'api_key': KEY,
                'models': {'fixture-model': {'protocol': 'chat', 'context_tokens': 32768}}}}},
            'limits': {'low_price_input': False, 'request_timeout_ms': 40000, 'task_timeout_ms': 120000},
        }
        config_path = home / '.thin/config.json'
        config_bytes = json.dumps(config).encode()
        config_path.write_bytes(config_bytes)
        config_path.chmod(0o600)

        master, slave = pty.openpty()
        fcntl.ioctl(slave, termios.TIOCSWINSZ, struct.pack('HHHH', ROWS, columns, 0, 0))
        original = termios.tcgetattr(slave)
        original_flags = fcntl.fcntl(slave, fcntl.F_GETFL)

        def child_setup():
            os.setsid()
            fcntl.ioctl(0, termios.TIOCSCTTY, 0)

        child = subprocess.Popen([app, '--no-model-auto-refresh'], stdin=slave, stdout=slave,
                                 stderr=slave, cwd=project, preexec_fn=child_setup,
                                 env={'PATH': '/usr/bin:/bin', 'HOME': str(home),
                                      'XDG_RUNTIME_DIR': str(runtime), 'LANG': 'C.UTF-8',
                                      'TERM': 'xterm-256color'})
        screen = Screen(columns)
        capture = bytearray()

        def pump_until(predicate, what, timeout=12):
            deadline = time.monotonic() + timeout
            while time.monotonic() < deadline:
                if control.failure is not None:
                    raise control.failure
                if predicate():
                    return
                ready, _, _ = select.select([master], [], [], min(.05, max(0, deadline - time.monotonic())))
                if ready:
                    try:
                        data = os.read(master, 65536)
                    except OSError as error:
                        if error.errno != errno.EIO:
                            raise
                        data = b''
                    if data:
                        capture.extend(data)
                        assert len(capture) <= 2 * 1024 * 1024, 'PTY capture bound'
                        screen.feed(data)
                if child.poll() is not None and not predicate():
                    raise AssertionError(f'app exited early ({child.returncode}) while waiting for {what}')
            raise AssertionError(f'timed out waiting for {what}')

        def fresh(marker=b''):
            """True only when the newest completed frame carries `marker` and is idle.

            Frame authority is the real FRAME_END sequence plus the borrowed
            Screen's settled-composer oracle: never a literal '>' or a sleep.
            """
            end = capture.rfind(FRAME_END)
            if end < 0:
                return False
            if capture.find(SYNC_BEGIN, end) >= 0:
                return False  # a newer frame is still unfinished and owns no authority
            previous = capture.rfind(FRAME_END, 0, end)
            start = previous + len(FRAME_END) if previous >= 0 else 0
            return capture.find(marker, start, end) >= 0 and screen.idle()

        def send(data):
            assert child.poll() is None, 'owned child already exited'
            os.write(master, data)

        try:
            pump_until(lambda: fresh(), 'first acknowledged idle composer')
            assert screen.row == len(screen.grid) - 1, 'initial composer is not on the physical bottom row'
            pgid = os.getpgid(child.pid)
            assert pgid == child.pid, 'owned child does not lead its own process group'

            # Round 1: the primary answers immediately, then the Memory helper is
            # held unanswered on a fixture-owned Event.
            control.expect(PROMPTS[0])
            send(PROMPTS[0].encode() + b'\r')
            pump_until(lambda: b'answer-one-proof' in capture and footer_state(screen) == ACTIVE,
                       'round 1 idle primary with an active Memory footer')
            hint = assert_footer(screen, ACTIVE)
            rows = [row_text(screen, i) for i in range(len(screen.grid))]
            assert any(marker in text for text in rows for marker in WARNING_MARKERS), \
                f'expected the benign capability warning to be visible: {rows!r}'
            assert control.helper1_arrived.wait(12), 'Memory 1 request did not arrive'
            assert control.helper == 1 and control.primary == 1
            assert_no_memory_transcript(screen)

            # Round 2 while Memory 1 is still unanswered: the primary must be
            # admitted, answer and settle without releasing Memory 1.
            queued_one = ACTIVE + ' (queued: 1)'
            control.expect(PROMPTS[1])
            send(PROMPTS[1].encode() + b'\r')
            pump_until(lambda: control.primary == 2 and b'answer-two-proof' in capture and screen.idle()
                       and footer_state(screen) == queued_one,
                       'round 2 primary answer while Memory 1 is blocked')
            assert not control.release1.is_set(), 'Memory 1 was released before round 2 settled'
            assert control.helper == 1, 'Memory 2 started before Memory 1 finished (FIFO violated)'
            assert footer_state(screen) == queued_one, f'Memory footer lost while queued: {footer_state(screen)!r}'
            assert_footer(screen, queued_one)
            assert_no_memory_transcript(screen)

            # Release Memory 1 with valid evidence; the queued job must then run on
            # a fresh generation whose related set carries the committed fact.
            control.release1.set()
            assert control.helper2_arrived.wait(12), 'queued Memory 2 request did not arrive'
            with control.lock:
                materials = list(control.materials)
            assert len(materials) == 2, f'Memory material count {len(materials)} != 2'
            related = [entry for entry in materials[1].get('related') or []
                       if entry.get('category') == 'preferences' and entry.get('topic') == 'review-style']
            assert related and related[0].get('content') == FACT, \
                f'queued Memory 2 related set lacks the committed fact: {materials[1].get("related")!r}'
            assert VERSION.fullmatch(str(related[0].get('version'))), 'queued Memory 2 related version is not 64 hex'
            saved = project / SAVED_PATH
            assert saved.is_file(), 'committed Memory fact file is missing'
            saved_text = saved.read_text(encoding='utf-8')
            assert FACT in saved_text and KEY not in saved_text, 'committed fact file content mismatch'

            # Empty extraction result: the terminal footer is the documented
            # "no new durable entries" label, not a transcript notice.
            control.release2.set()
            pump_until(lambda: footer_state(screen) == TERMINAL_SKIPPED and screen.idle(),
                       'terminal Memory footer "no new durable entries"')
            assert_footer(screen, TERMINAL_SKIPPED)
            assert_no_memory_transcript(screen)

            # Round 3 then exit while its Memory request is unanswered: Ctrl-D from
            # the idle composer must not release a valid response for the job.
            control.expect(PROMPTS[2])
            send(PROMPTS[2].encode() + b'\r')
            pump_until(lambda: control.helper3_arrived.is_set() and footer_state(screen) == ACTIVE,
                       'round 3 active Memory footer after prompt 3')
            assert b'answer-three-proof' in capture, 'round 3 primary answer is missing'
            assert_footer(screen, ACTIVE)
            assert_no_memory_transcript(screen)
            assert not control.release3.is_set() and not control.helper3_responded

            send(b'\x04')
            pump_until(lambda: child.poll() is not None, 'Ctrl-D exit while Memory is active', timeout=10)
            assert child.wait(timeout=5) == 0, 'owned child did not exit cleanly from an idle Ctrl-D'
            assert control.helper3_canceled.wait(3), 'owned server did not observe the canceled Memory socket'
            assert not control.helper3_responded, 'a canceled Memory request received a valid response'

            # Strict counts: no primary retry, no auxiliary replay, no second job.
            assert control.primary == 3, f'primary requests {control.primary} != 3'
            assert control.helper == 3, f'Memory requests {control.helper} != 3'
            journals = list((project / '.thin/sessions').glob('*.jsonl'))
            assert journals, 'accepted session journal missing'
            assert len(journals) <= 16, 'session journal count bound'
            def check_records(value):
                if isinstance(value, dict):
                    if value.get('role') in ('user', 'assistant'):
                        content = value.get('content')
                        if isinstance(content, str):
                            assert 'Memory:' not in content, 'Memory notice in canonical message'
                    for nested in value.values():
                        check_records(nested)
                elif isinstance(value, list):
                    for nested in value:
                        check_records(nested)
            for journal in journals:
                assert journal.stat().st_size <= 4 * 1024 * 1024, 'session journal byte bound'
                for line in journal.read_text(encoding='utf-8').splitlines():
                    check_records(json.loads(line))
            for retired in RETIRED_PATHS:
                assert not (project / retired).exists(), f'retired Memory jobs path recreated: {retired}'
            assert config_path.read_bytes() == config_bytes, 'active config was rewritten by the fixture run'
            assert termios.tcgetattr(slave) == original, 'termios was not restored'
            assert fcntl.fcntl(slave, fcntl.F_GETFL) == original_flags, 'tty flags were not restored'
            assert child.pid and pgid == child.pid
            print(f'PASS memory-background columns={columns}: primary=3 helper=3 '
                  f'prompt2_admitted_while_memory=1 queued_fifo=1 helper2_related_version=1 '
                  f'terminal_no_new_entries=1 transcript_memory_rows=0 ctrl_d_cancel=1')
        finally:
            control.release1.set()
            control.release2.set()
            control.release3.set()
            if child is not None and child.poll() is None:
                try:
                    os.killpg(pgid if pgid is not None else child.pid, signal.SIGTERM)
                except (ProcessLookupError, PermissionError):
                    child.terminate()
                try:
                    child.wait(timeout=3)
                except subprocess.TimeoutExpired:
                    try:
                        os.killpg(pgid if pgid is not None else child.pid, signal.SIGKILL)
                    except (ProcessLookupError, PermissionError):
                        child.kill()
                    child.wait(timeout=3)
            for fd in (master, slave):
                if fd is not None:
                    try:
                        os.close(fd)
                    except OSError:
                        pass
            server.shutdown()
            server.server_close()
            thread.join(timeout=3)


if __name__ == '__main__':
    app = str(Path(sys.argv[1]).resolve(strict=True))
    for columns in COLUMNS:
        run(app, columns)
    print(f'PASS test-memory-background: {len(COLUMNS)} owned PTYs, primary=6 helper=6, '
          'next prompt admitted while owned Memory runs')
