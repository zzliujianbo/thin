#!/usr/bin/env python3
"""Owned PTY acceptance: a later prompt is admitted while owned Memory still runs.

The real thin binary is launched in its own PTY against a generated HOME,
project, runtime directory and config. The only network is the loopback Chat
server this fixture owns. Primary rounds and auxiliary Memory rounds share that
server and are distinguished by the extractor system-instruction prefix, so the
interactive lifecycle can be observed without any fake unit interface.

Contract under test (interactive session only; the headless fixture is separate):
  * The primary Runtime reaches a finished/idle state after its Memory job is
    enqueued, so the next prompt is admitted instead of becoming a follow-up.
  * Memory jobs are FIFO: the second extractor request never starts before the
    first one has been answered.
  * The footer holds exactly one Memory hint directly above the first composer
    row, with a blank separator above the hint. Active Memory is the row prefix even next to the
    benign capability warning, and terminal Memory results never become
    transcript rows.
  * The queued Memory suffix carries a count, never the primary S:/F: counters.
  * The queued job's material is a fresh generation: it carries the committed
    fact and its version in `related`.
  * Leaving while Memory is active is bounded; the owned server observes the
    closed socket and never releases a valid response for the canceled job.

Nothing here reads user state: HOME, project, XDG_RUNTIME_DIR and config live in
one TemporaryDirectory, the credential is generated by this fixture, and no real
config, history, .thin or metadata of the developer is touched.
"""
import errno
import fcntl
